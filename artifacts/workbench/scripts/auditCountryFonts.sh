#!/usr/bin/env bash
# Repeatable font audit for the structured country briefs (PNG / West Papua /
# Indonesia). Exports each brief headlessly (reading live data straight from
# Postgres — no owner-gated API or running server needed) and refreshes the
# country block of screenshots/font_proof/FONT_AUDIT.txt with a per-page
# Tf-operator font inventory. PASS = only /Roboto fonts are ever selected.
# Idempotent: the country block (below the SENTINEL) is regenerated each run,
# while everything above it (shipping / jakarta sections) is preserved.
#
# Run from the workbench package root:
#   PROD_DATABASE_URL=... bash scripts/auditCountryFonts.sh
set -euo pipefail

cd "$(dirname "$0")/.."
# shellcheck source=resolveProdDatabaseUrl.sh
source "$(dirname "$0")/resolveProdDatabaseUrl.sh"
OUT_DIR="screenshots/font_proof"
AUDIT_FILE="$OUT_DIR/FONT_AUDIT.txt"
SENTINEL="==== COUNTRY STRUCTURED BRIEFS (auto-generated by auditCountryFonts.sh) ===="
mkdir -p "$OUT_DIR"

declare -A SLUGS=(
  ["png_country"]="papua-new-guinea"
  ["west_papua_country"]="papua"
  ["indonesia_country"]="indonesia"
)

ARGS=()
for name in png_country west_papua_country indonesia_country; do
  slug="${SLUGS[$name]}"
  pdf="$OUT_DIR/${name}.pdf"
  echo ">> Exporting $slug -> $pdf"
  TOPIC=country COUNTRY_SLUG="$slug" OUT_PATH="$pdf" \
    npx tsx --import ./scripts/registerLoader.mjs scripts/exportReportPdfHeadless.ts
  ARGS+=("${name}.pdf (${slug})::$pdf")
done

echo ">> Auditing fonts"
set +e
COUNTRY_BLOCK="$(python3 scripts/fontAuditTf.py "${ARGS[@]}")"
STATUS=$?
set -e

# Preserve everything above the sentinel (shipping / jakarta), then regenerate
# the country block below it so reruns are idempotent.
if [ -f "$AUDIT_FILE" ]; then
  awk -v s="$SENTINEL" 'index($0, s){exit} {print}' "$AUDIT_FILE" > "$AUDIT_FILE.tmp"
else
  : > "$AUDIT_FILE.tmp"
fi
{
  printf '%s\n\n' "$SENTINEL"
  printf 'Audit method: per-page content-stream Tf-operator inventory (resolves each\n'
  printf 'selected font resource back to its BaseFont). Only /Roboto* may be SELECTED\n'
  printf 'by a Tf operator. PASS = no non-Roboto font is ever selected.\n\n'
  printf '%s\n' "$COUNTRY_BLOCK"
} >> "$AUDIT_FILE.tmp"
mv "$AUDIT_FILE.tmp" "$AUDIT_FILE"

echo ">> Wrote $AUDIT_FILE"
exit $STATUS
