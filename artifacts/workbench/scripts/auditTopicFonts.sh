#!/usr/bin/env bash
# Repeatable font audit for the TOPIC reports (shipping / fuel / cargo_watch /
# flashpoint). Exports each report headlessly (reading live data straight from
# Postgres — no owner-gated API or running server needed) and refreshes the
# topic block at the TOP of screenshots/font_proof/FONT_AUDIT.txt with a
# per-page Tf-operator font inventory. PASS = only /Roboto fonts are ever
# selected. Mirrors scripts/auditCountryFonts.sh (the country side) and exits
# non-zero if any non-Roboto font is selected, so it is safe to wire into a
# validation step / CI.
#
# Idempotent: the topic block (above SENTINEL) is regenerated each run, while
# everything from the jakarta_country / country sentinel down is preserved.
#
# Run from the workbench package root:
#   DATABASE_URL=... bash scripts/auditTopicFonts.sh
set -euo pipefail

cd "$(dirname "$0")/.."
OUT_DIR="screenshots/font_proof"
AUDIT_FILE="$OUT_DIR/FONT_AUDIT.txt"
SENTINEL="==== TOPIC REPORTS (auto-generated by auditTopicFonts.sh) ===="
# Markers that begin the blocks owned by other audit scripts; the first one
# found marks where this script's regenerated topic block must stop.
JAKARTA_MARKER="==== jakarta_country.pdf"
COUNTRY_SENTINEL="==== COUNTRY STRUCTURED BRIEFS (auto-generated by auditCountryFonts.sh) ===="
mkdir -p "$OUT_DIR"

# Topic -> the TOPIC env value exportReportPdfHeadless.ts routes on. The report
# id is resolved to the LATEST report of each family inside the exporter when
# REPORT_ID is unset, so no fragile id pins live here.
TOPICS=(shipping fuel cargo_watch flashpoint)

ARGS=()
for topic in "${TOPICS[@]}"; do
  pdf="$OUT_DIR/${topic}_report.pdf"
  echo ">> Exporting $topic -> $pdf"
  TOPIC="$topic" OUT_PATH="$pdf" \
    npx tsx --import ./scripts/registerLoader.mjs scripts/exportReportPdfHeadless.ts
  ARGS+=("${topic}_report.pdf (${topic})::$pdf")
done

echo ">> Auditing fonts"
set +e
TOPIC_BLOCK="$(python3 scripts/fontAuditTf.py "${ARGS[@]}")"
STATUS=$?
set -e

# Regenerate the topic block at the top, then preserve everything from the first
# downstream sentinel (jakarta_country or the country block) onward so reruns are
# idempotent and never clobber the other scripts' sections.
TAIL=""
if [ -f "$AUDIT_FILE" ]; then
  TAIL="$(awk -v a="$JAKARTA_MARKER" -v b="$COUNTRY_SENTINEL" \
    'found{print; next} index($0,a)==1 || index($0,b)==1 {found=1; print}' \
    "$AUDIT_FILE")"
fi
{
  printf '%s\n\n' "$SENTINEL"
  printf 'Audit method: per-page content-stream Tf-operator inventory (resolves each\n'
  printf 'selected font resource back to its BaseFont). jsPDF auto-registers the 14\n'
  printf 'standard PDF fonts in the font dictionary, but only /Roboto* may be SELECTED\n'
  printf 'by a Tf operator. PASS = no non-Roboto font is ever selected.\n\n'
  printf '%s\n' "$TOPIC_BLOCK"
  if [ -n "$TAIL" ]; then
    printf '\n%s\n' "$TAIL"
  fi
} > "$AUDIT_FILE.tmp"
mv "$AUDIT_FILE.tmp" "$AUDIT_FILE"

echo ">> Wrote $AUDIT_FILE"
exit $STATUS
